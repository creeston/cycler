/**
 * Small deterministic PRNG (mulberry32). The routing strategies draw from it
 * instead of Math.random so that the same seed reproduces the same routes,
 * and synthetic fixtures are the same on every run.
 */
export function seededRandom(seed: number): () => number {
  let state = seed >>> 0
  return () => {
    state = (state + 0x6d2b79f5) >>> 0
    let t = state
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}
